"""Figure S1 — APGI Onset Ignition Timeline (0–600 ms).

Multi-track schematic showing normalised APGI variable magnitudes:
  • Sₜ      — precision-weighted prediction-error signal  (paper Eq. 1)
  • θₜ      — allostatic threshold                        (paper Eq. 3)
  • Πᵉ      — exteroceptive effective precision
  • Πⁱ_eff  — interoceptive effective precision           (paper §4.2)

All four variables are normalised to [0, 1] so they are commensurable on
a single y-axis, as specified in the paper's Figure S1 caption.

Annotation tracks correspond to Table 3 (onset ignition timeline):
  Phase 1   0– 80 ms : ε initiation           | N1 / P1
  Phase 2  80–150 ms : Π weighting             | α suppression
  Phase 3 150–300 ms : Sₜ accumulation         | N2 / γ onset
  Phase 4 300–400 ms : Ignition decision        | P3b onset
  Phase 5 400–500 ms : Global broadcast         | Sustained LPC
  Phase 6 ≥500 ms    : Refractory reset         | α rebound

Simulation:
  The four traces are generated by integrating the paper's ODEs
  (Equations 1–4) directly at 1 ms resolution.  This guarantees that
  the figure reflects the publication equations without interference from
  pipeline implementation details that are irrelevant to the illustration.

Usage:
    python examples/figure_s1.py          # saves outputs/figure_s1.png
    make figure-s1                        # via Makefile

Output:
    outputs/figure_s1.png  — 300 dpi publication-ready PNG
"""

